\set ON_ERROR_STOP on
begin;
create function pg_temp.assert(ok boolean,message text) returns void language plpgsql as $$
begin if ok is distinct from true then raise exception 'FAIL: %',message;end if;end $$;
insert into auth.users(id,email,email_confirmed_at) values('10000000-0000-0000-0000-000000000010','notify@example.test',now());
insert into auth.sessions(id,user_id) values('20000000-0000-0000-0000-000000000010','10000000-0000-0000-0000-000000000010');
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"10000000-0000-0000-0000-000000000010","session_id":"20000000-0000-0000-0000-000000000010"}',true);
select public.put_push_subscription('{"endpoint":"https://fcm.googleapis.com/test","keys":{"p256dh":"public-key","auth":"auth-key"}}');
select pg_temp.assert(public.push_subscription_status('https://fcm.googleapis.com/test'),'subscription belongs to current live session');
select public.schedule_rest(30);
select public.schedule_rest(60);
reset role;
select pg_temp.assert((select count(*)=1 from private.notification_jobs),'extension replaces old rest job');
select pg_temp.assert((select due_at>now()+interval '50 seconds' from private.notification_jobs),'extended deadline retained');
set local role authenticated;
select public.cancel_rest();
reset role;
update private.notification_jobs set due_at=now()-interval '1 second';
set local role service_role;
select pg_temp.assert(public.claim_notifications() = '[]'::jsonb,'cancelled job never claimed');
reset role;
set local role authenticated;
select public.schedule_rest(1);
reset role;
update private.notification_jobs set due_at=now()-interval '1 second';
set local role service_role;
create temporary table claimed as select public.claim_notifications() as jobs;
select pg_temp.assert(jsonb_array_length(jobs)=1,'due job claimed') from claimed;
select pg_temp.assert(public.claim_notifications()='[]'::jsonb,'lease prevents a second claim');
select pg_temp.assert(jsonb_array_length(public.notification_targets((jobs->0->>'id')::uuid,(jobs->0->>'lease')::uuid))=1,'only active subscriptions targeted') from claimed;
reset role;
set local role authenticated;
select public.cancel_rest();
reset role;
set local role service_role;
select pg_temp.assert(public.notification_targets((jobs->0->>'id')::uuid,(jobs->0->>'lease')::uuid)='[]'::jsonb,'cancel invalidates in-flight claim') from claimed;
reset role;
update private.notification_jobs set status='pending',attempts=3,lease=null,lease_until=null,due_at=now()-interval '1 second';
set local role service_role;
create temporary table fourth_attempt as select public.claim_notifications() as jobs;
select public.claim_notifications();
reset role;
select pg_temp.assert((select status='sending' and attempts=4 and lease is not null from private.notification_jobs),'fourth live attempt survives another worker claim');
delete from auth.sessions where user_id='10000000-0000-0000-0000-000000000010';
select pg_temp.assert(not exists(select 1 from private.push_subscriptions s join auth.sessions a on a.id::text=s.session_id),'signed-out subscription inactive');
set local role authenticated;
select pg_temp.assert(not public.push_subscription_status('https://fcm.googleapis.com/test'),'revoked browser binding is not shown enabled');
reset role;
rollback;
